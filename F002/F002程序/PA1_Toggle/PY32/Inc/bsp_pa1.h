/* 防止头文件重复包含 ------------------------------------------------*/
#ifndef __BSP_PA1_H
#define __BSP_PA1_H

#include "py32f0xx_hal.h"

/* 电平定义 ----------------------------------------------------------*/
#define PA1_ON   GPIO_PIN_SET      /* PA1 输出高电平 */
#define PA1_OFF  GPIO_PIN_RESET    /* PA1 输出低电平 */

/* 对外函数声明 ------------------------------------------------------*/
void BSP_PA1_Init(void);           /* 初始化 PA1 为推挽输出，默认低电平 */
void BSP_PA1_Set(uint8_t level);   /* 设置 PA1 电平：PA1_ON / PA1_OFF */
void BSP_PA1_Toggle(void);         /* 翻转 PA1 电平 */

#endif /* __BSP_PA1_H */


#include "main.h"

/**
  * @brief  全局 MSP 初始化（HAL_Init 内部调用）
  */
void HAL_MspInit(void)
{
  __HAL_RCC_SYSCFG_CLK_ENABLE();   /* 系统配置时钟：EXTI/引脚复用等功能需要 */
  __HAL_RCC_PWR_CLK_ENABLE();      /* 电源管理时钟：低功耗模式需要          */
}

